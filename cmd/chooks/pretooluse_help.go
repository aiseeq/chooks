package main

// preToolUseLong — справка pre-tool-use: какие проверки идут перед вызовом
// инструмента, что каждая отклоняет и почему. Карточки инструментов агентов
// собираются из справки, так агент видит причину отказа до вызова
const preToolUseLong = `Проверки перед вызовом инструмента (PreToolUse). Отказ проверки движка — код 2,
причина и подсказка — в stderr, их читает модель. Проверку включает ключ
tools.<имя>.enabled в config.yaml. Без ключа включены git_guard, rsync_guard,
pgrep_ancestors и understand_check, остальные выключены.

Отказывают:
  kill_guard (Bash, Monitor) — kill, pkill, killall, killall5, цель которых до
    запуска не проверить (PID из переменной или $(…), цели через xargs и
    parallel, скрипт из ввода, имя команды из $(…)), и сигнал, который заденет
    сессию или систему: PID 1, kill -1 (все процессы пользователя), kill 0 и
    группа процессов, предки хука (claude, оболочка, терминал), процессы, на
    которых держится сессия пользователя (systemd, dbus, kwin и подобные),
    pkill -f с шаблоном, совпадающим с текстом своей же команды. Команда,
    которую не разобрать, — тоже отказ.
  rm_guard (Bash, Monitor) — rm и rmdir, на которых Claude Code сам остановит
    команду запросом пользователю, который не снимается и в bypassPermissions:
    путь из возможно пустой переменной, относительный глоб после cd. И
    удаление рабочей папки самой оболочки. Отказ даёт переписанную форму.
  write_guard (Bash, Monitor) — запись файла через here-doc, тело которого
    Claude Code примет за rm по пустой переменной и остановит тем же запросом.
  rsync_guard (Bash, Monitor) — rsync с --delete, --del или --delete-*, если
    назначение раскрывается при запуске (переменная, подстановка): пустое
    значение удалит не то. "${R:?}" и литеральный путь проходят.
  git_guard (Bash, Monitor) — суб-агентам, не основной сессии: git-команды,
    которые стирают незакоммиченную работу или меняют запушенное и общее:
    reset --hard, restore, checkout и switch с потерей правок, clean, stash,
    rm без --cached, reflog expire, force-push, удаление ветки на remote.
    В своём linked worktree и во временном каталоге суб-агенту можно то, что
    меняет только это дерево. Основная сессия делает такое по «да» пользователя.
  model_guard (Agent, Bash, Monitor) — модель не из ~/.config/models/approved:
    model у Agent; --model, --fallback-model, --settings, --agents и
    переменные вроде ANTHROPIC_MODEL у claude; --model, -m и -c у codex;
    --model и -m у opencode.
  jira_style (Bash) — curl с комментарием в Jira, текст которого написан мимо
    скилла write-as-user: длинное тире, markdown, типографские кавычки, оборот
    «X, а не Y», приветствие, число прописью.

Не отказывает:
  pgrep_ancestors (Bash, Monitor) — дописывает -A к pgrep -f (подмена входа
    в stdout): иначе pgrep находит оболочку своей же команды, и цикл «ждать,
    пока процесс кончится» не кончается.

Отдельной подкомандой, своей строкой хука в settings.json:
  understand-check (ключ understand_check; SendMessage, Edit, Write, Bash) —
    судья без контекста беседы сверяет письмо другой сессии и правку
    инструкций с репликой пользователя. Расхождение — отказ один раз (JSON
    permissionDecision deny в stdout); тот же вызов повтором проходит.
    Суб-агентов не проверяет.`
