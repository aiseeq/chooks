package claimcheck

import "testing"

func TestHasFactSignal(t *testing.T) {
	skipped := map[string]string{
		"вопрос":   "Делать так или подождать, пока лид посмотрит?",
		"план":     "Сначала посмотрю журнал, потом поправлю конфиг и проверю.",
		"согласие": "Хорошо, понял, так и сделаю.",
	}
	for name, text := range skipped {
		if HasFactSignal(text) {
			t.Errorf("%s: %q должен отсеиваться", name, text)
		}
	}
	kept := map[string]string{
		"число":            "Осталось 3 строки.",
		"дата":             "Срок — 26.11.",
		"имя файла":        "Правка в main.go.",
		"путь":             "Лог лежит в ~/logs, смотри там.",
		"работает":         "Теперь Работает как надо.",
		"нет":              "Нет, такого флага нет.",
		"есть":             "Такой флаг есть.",
		"прошёл":           "Тест прошёл.",
		"упало":            "Всё упало.",
		"готово":           "Готово.",
		"имя в конце":      "смотри design.md",
		"путь в начале":    "/etc/hosts правлен",
		"имя в скобках":    "(см. design.md)",
		"латиница и цифры": "версия v2 вышла",
	}
	for name, text := range kept {
		if !HasFactSignal(text) {
			t.Errorf("%s: %q не должен отсеиваться", name, text)
		}
	}
	for _, text := range []string{"т.е. так и сделаю", "работа идёт по плану", "готовлю план"} {
		if HasFactSignal(text) {
			t.Errorf("%q: сокращение и однокоренные слова — не признак", text)
		}
	}
}
